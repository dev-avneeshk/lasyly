// Parses scripts/quiz/nba-501-1000.raw.txt and emits lib/quiz/nba-501-1000.ts,
// exporting the questions 501-1000 as themed `Quiz` objects across the four NBA
// categories. Run: node scripts/quiz/generate-nba-501-1000.mjs

import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

const __dirname = dirname(fileURLToPath(import.meta.url))
const raw = readFileSync(join(__dirname, "nba-501-1000.raw.txt"), "utf8")

const LETTER_TO_INDEX = { A: 0, B: 1, C: 2, D: 3, E: 4, F: 5 }

const lines = raw.split("\n")
const questions = []
let cur = null

const startRe = /^(\d+)\.\s+(.*)$/
const optRe = /^([A-F])\)\s+(.*)$/
const ansRe = /^Answer:\s+([A-F])\b/

for (const line of lines) {
  const t = line.trim()
  if (!t) continue
  let m
  if ((m = t.match(ansRe))) {
    if (!cur) throw new Error(`Answer with no question: ${t}`)
    // If this question already has an answer, ignore duplicate answer lines.
    if (cur.answer === -1) cur.answer = LETTER_TO_INDEX[m[1]]
    questions.push(cur)
    cur = null
  } else if ((m = t.match(optRe)) && cur) {
    cur.options.push(m[2])
  } else if ((m = t.match(startRe))) {
    if (cur) throw new Error(`Question ${cur.num} had no answer`)
    cur = { num: Number(m[1]), prompt: m[2], options: [], answer: -1 }
  }
}
if (cur) throw new Error(`Trailing question ${cur.num} had no answer`)

if (questions.length !== 500) {
  throw new Error(`Expected 500 questions, parsed ${questions.length}`)
}
for (const q of questions) {
  if (q.options.length < 2) throw new Error(`Q${q.num} has < 2 options`)
  if (q.answer < 0 || q.answer >= q.options.length) {
    throw new Error(`Q${q.num} has out-of-range answer ${q.answer}`)
  }
}

// Theme -> category mapping for 501-1000.
function categoryFor(num) {
  if (num >= 501 && num <= 520) return "nba-players" // nicknames
  if (num >= 521 && num <= 555) return "nba-history" // Finals matchups & playoff moments
  if (num >= 556 && num <= 575) return "nba-players" // scoring & triple-double feats
  if (num >= 576 && num <= 601) return "nba-players" // MJ Wizards, numbers, shooting, contests
  if (num >= 602 && num <= 614) return "nba-players" // dunk/skills contests
  if (num >= 615 && num <= 832) return "nba-players" // draft & trade lore
  if (num >= 833 && num <= 874) return "nba-teams" // trades, coaches, franchises
  if (num >= 875 && num <= 893) return "nba-general" // systems, moves, tactics
  if (num >= 894 && num <= 912) return "nba-players" // All-Star lore
  if (num >= 913 && num <= 928) return "nba-history" // Finals/Conf MVPs
  if (num >= 929 && num <= 941) return "nba-players" // scoring & All-Star MVPs
  if (num >= 942 && num <= 962) return "nba-teams" // origins, numbers, arenas
  if (num >= 963 && num <= 973) return "nba-players" // culture & Linsanity
  if (num >= 974 && num <= 1000) return "nba-history" // playoff moments & lore
  return "nba-history"
}

// Collapse to three buckets: player, team, mixed.
function bucketFor(num) {
  const cat = categoryFor(num)
  if (cat === "nba-players") return "player"
  if (cat === "nba-teams") return "team"
  return "mixed" // general + history
}

function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')
}

let out = ""
out += "// AUTO-GENERATED by scripts/quiz/generate-nba-501-1000.mjs — do not edit by hand.\n"
out += "// Source: scripts/quiz/nba-501-1000.raw.txt (NBA questions 501-1000).\n"
out += "// Re-run the generator to regenerate.\n\n"
out += 'import type { BankQuestion } from "./types"\n\n'
out += "export const NBA_1000_QUESTIONS: BankQuestion[] = [\n"

for (const q of questions) {
  out += "  {\n"
  out += `    id: "nba-1000-q${q.num}",\n`
  out += `    bucket: "${bucketFor(q.num)}",\n`
  out += `    prompt: "${esc(q.prompt)}",\n`
  out += `    options: [${q.options.map((o) => `"${esc(o)}"`).join(", ")}],\n`
  out += `    answer: ${q.answer},\n`
  out += "  },\n"
}
out += "]\n"

const target = join(__dirname, "..", "..", "lib", "quiz", "nba-501-1000.ts")
writeFileSync(target, out)
console.log(`Wrote ${questions.length} questions to ${target}`)
