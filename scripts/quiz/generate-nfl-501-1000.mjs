// Parses scripts/quiz/nfl-501-1000.raw.txt and emits lib/quiz/nfl-501-1000.ts,
// exporting questions 501-1000 as a flat, bucketed BankQuestion[] across the
// three NFL categories (player/team/mixed).
// Run: node scripts/quiz/generate-nfl-501-1000.mjs

import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"
import { deriveDifficulty } from "./difficulty.mjs"
import { deriveBucket } from "./nfl-bucket.mjs"

const __dirname = dirname(fileURLToPath(import.meta.url))
const raw = readFileSync(join(__dirname, "nfl-501-1000.raw.txt"), "utf8")

const LETTER_TO_INDEX = { A: 0, B: 1, C: 2, D: 3, E: 4, F: 5 }

const lines = raw.split("\n")
const questions = []
let cur = null

const startRe = /^(\d+)\.\s+(.*)$/
const optRe = /^([A-F])\)\s+(.*)$/
const ansRe = /^Answer:\s+([A-F])\b/

for (const line of lines) {
  const t = line.trim()
  if (!t) continue
  let m
  if ((m = t.match(ansRe))) {
    if (!cur) throw new Error(`Answer with no question: ${t}`)
    if (cur.answer === -1) cur.answer = LETTER_TO_INDEX[m[1]]
    questions.push(cur)
    cur = null
  } else if ((m = t.match(optRe)) && cur) {
    cur.options.push(m[2])
  } else if ((m = t.match(startRe))) {
    if (cur) throw new Error(`Question ${cur.num} had no answer`)
    cur = { num: Number(m[1]), prompt: m[2], options: [], answer: -1 }
  }
}
if (cur) throw new Error(`Trailing question ${cur.num} had no answer`)

if (questions.length !== 500) {
  throw new Error(`Expected 500 questions, parsed ${questions.length}`)
}
for (const q of questions) {
  if (q.options.length < 2) throw new Error(`Q${q.num} has < 2 options`)
  if (q.answer < 0 || q.answer >= q.options.length) {
    throw new Error(`Q${q.num} has out-of-range answer ${q.answer}`)
  }
}

function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')
}

let out = ""
out += "// AUTO-GENERATED by scripts/quiz/generate-nfl-501-1000.mjs — do not edit by hand.\n"
out += "// Source: scripts/quiz/nfl-501-1000.raw.txt (NFL questions 501-1000).\n"
out += "// Re-run the generator to regenerate.\n\n"
out += 'import type { BankQuestion } from "./types"\n\n'
out += "export const NFL_1000_QUESTIONS: BankQuestion[] = [\n"

for (const q of questions) {
  out += "  {\n"
  out += `    id: "nfl-1000-q${q.num}",\n`
  out += `    bucket: "${deriveBucket(q.prompt, q.options)}",\n`
  out += `    difficulty: "${deriveDifficulty(q.prompt)}",\n`
  out += `    prompt: "${esc(q.prompt)}",\n`
  out += `    options: [${q.options.map((o) => `"${esc(o)}"`).join(", ")}],\n`
  out += `    answer: ${q.answer},\n`
  out += "  },\n"
}
out += "]\n"

const target = join(__dirname, "..", "..", "lib", "quiz", "nfl-501-1000.ts")
writeFileSync(target, out)
console.log(`Wrote ${questions.length} questions to ${target}`)
