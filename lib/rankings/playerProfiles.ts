// Design notes (see product spec):
//   • For established stars we use their recognizable real nicknames
//     (e.g. Stephen Curry → "Chef Curry", LeBron James → "King James").
//   • For rookies, fringe players, and obscure names we use a custom UI
//     nickname (e.g. "Rising Prospect", "The Ceiling is still rising") rather
//     than pretending it is an official nickname.
//
// Anything NOT present here falls back to the score-derived generic generator
// in `explanations.ts`, so the map only needs to cover known players.
//
// Matching is accent- and punctuation-insensitive so names like
// "Nikola Jokić", "Alperen Şengün", or "Luka Dončić" resolve correctly.

export interface PlayerProfile {
  /** Display quote — rendered as the italic signature line. */
  quote: string
  /** Display nickname — rendered as the "— NICKNAME" attribution. */
  nickname: string
}

/**
 * Normalize a player name for lookup: strip diacritics, lowercase, and reduce
 * to alphanumerics separated by single spaces. Keeps matching resilient to
 * accents, punctuation (periods, apostrophes), and casing differences.
 */
export function normalizePlayerName(name: string): string {
  return name
    .normalize("NFD")               // split accented chars into base + combining mark
    .replace(/[\u0300-\u036f]/g, "") // strip the combining marks
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")     // collapse punctuation/whitespace to single spaces
    .trim()
}

