/**
 * Curated profiles keyed by NORMALIZED name for fast, accent-insensitive lookup.
 * Built once at module load from RAW_PROFILES.
 */
const PROFILE_LOOKUP: Map<string, PlayerProfile> = new Map(
  Object.entries(RAW_PROFILES).map(([name, profile]) => [normalizePlayerName(name), profile])
)

/**
 * Look up a curated profile for a player by name. Returns undefined when the
 * player isn't in the curated list (caller should fall back to generic
 * generation).
 */
export function getPlayerProfile(playerName: string | null | undefined): PlayerProfile | undefined {
  if (!playerName) return undefined
  return PROFILE_LOOKUP.get(normalizePlayerName(playerName))
}
